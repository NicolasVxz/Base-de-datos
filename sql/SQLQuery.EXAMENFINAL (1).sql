-- 8) REALIZAME UN REPORTE DE BOLETA POR CADA PACIENTE Y SUS CITAS
DECLARE @IdPac CHAR(10), @IdAnt CHAR(10)
DECLARE @Nom VARCHAR(25), @Ape VARCHAR(25)
DECLARE @Medico CHAR(25), @Espec CHAR(22), @Pago_Final CHAR(10), @Fecha CHAR(10)

SET @IdAnt = ''

DECLARE C_Reporte CURSOR LOCAL FOR
    SELECT P.IDPACIENTE, P.NOMBRE, P.APELLIDOS,
           M.NOM_MEDICO + ' ' + M.APE_MEDICO,
           E.NOM_ESPECI,
           CONVERT(VARCHAR(10), PG.PAGO_FINAL),
           CONVERT(VARCHAR(10), C.FECHA, 103)
    FROM CITA C
    INNER JOIN PACIENTE P       ON C.IDPACIENTE = P.IDPACIENTE
    INNER JOIN MEDICO M         ON C.IDMEDICO   = M.IDMEDICO
    INNER JOIN ESPECIALIDADES E ON M.IDESPECI   = E.IDESPECI
    INNER JOIN PAGO PG          ON C.IDCITA     = PG.IDCITA
    ORDER BY P.IDPACIENTE, C.FECHA

OPEN C_Reporte
FETCH C_Reporte INTO @IdPac, @Nom, @Ape, @Medico, @Espec, @Pago_Final, @Fecha

PRINT '                         REPORTE DE CITAS POR PACIENTE'
PRINT '                         *****************************'

WHILE @@FETCH_STATUS = 0
BEGIN
    IF @IdPac <> @IdAnt
    BEGIN
        PRINT ''
        PRINT 'Nombre del Paciente    : ' + @Nom
        PRINT 'Apellidos del Paciente : ' + @Ape
        PRINT ''
        PRINT '     MEDICO                   ESPECIALIDAD        PAGO FINAL     FECHA'
        SET @IdAnt = @IdPac
    END

    PRINT '     ' + @Medico + @Espec + @Pago_Final + @Fecha
    PRINT '     -------------------------------------------------------------------'

    FETCH C_Reporte INTO @IdPac, @Nom, @Ape, @Medico, @Espec, @Pago_Final, @Fecha
END

CLOSE C_Reporte
GO


-- 9) DECLARA UNA FUNCION PARA BUSCAR RECLAMOS DE USUARIOS POR SU ID DE PACIENTES
CREATE FUNCTION FN_RECLAMOS_PACIENTE (@IDPACIENTE CHAR(10))
RETURNS TABLE
AS
RETURN
(
    SELECT P.NOMBRE,
           P.APELLIDOS,
           R.IDRECLAMO,
           R.DESCRIP AS DESCRIPCION,
           R.ESTADORECLAMO AS ESTADO,
           R.FECREGIS AS FECHA_REGISTRO,
           R.FECSOLUCION AS FECHA_SOLUCION
    FROM PACIENTE P
    INNER JOIN RECLAMO R ON P.IDPACIENTE = R.IDPACIENTE
    WHERE P.IDPACIENTE = @IDPACIENTE
)
GO

