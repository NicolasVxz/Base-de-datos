-- 5) ¿CREAME UN PROCEDIMIENTO QUE INDIQUE ERRORES CONTROLADOS Y MENCIONANDO EL ERROR QUE SE HA GENERADO AL INGRESAR LOS DATOS?
ALTER PROCEDURE SP_INSERTAR_PACIENTE
@IDPACIENTE CHAR(10),
@NOMBRE VARCHAR(25),
@APELLIDOS VARCHAR(25),
@DNI CHAR(8),
@TELF VARCHAR(9),
@CORREO VARCHAR(25),
@DIREC VARCHAR(50),
@FECNAC DATE,
@TIPOSEGURO CHAR(5),
@IDADMI CHAR(5)
AS
BEGIN
    SET NOCOUNT ON
    BEGIN TRY
        -- Validaciones propias
        IF EXISTS (SELECT 1 FROM PACIENTE WHERE IDPACIENTE = @IDPACIENTE)
            THROW 50001, 'ERROR: El ID del paciente ya existe.', 1
        IF EXISTS (SELECT 1 FROM PACIENTE WHERE DNI = @DNI)
            THROW 50002, 'ERROR: Ya existe un paciente con ese DNI.', 1
        IF LEN(@DNI) <> 8
            THROW 50003, 'ERROR: El DNI debe tener 8 dígitos.', 1
        IF @FECNAC > GETDATE()
            THROW 50004, 'ERROR: La fecha de nacimiento no puede ser futura.', 1
        IF NOT EXISTS (SELECT 1 FROM SEGURO WHERE TIPOSEGURO = @TIPOSEGURO)
            THROW 50005, 'ERROR: El tipo de seguro no existe.', 1
        IF NOT EXISTS (SELECT 1 FROM ADMI WHERE IDADMI = @IDADMI)
            THROW 50006, 'ERROR: El administrador no existe.', 1

        DECLARE @EDAD INT
        SET @EDAD = DATEDIFF(YEAR, @FECNAC, GETDATE())
        BEGIN TRANSACTION
        INSERT INTO PACIENTE(IDPACIENTE, NOMBRE, APELLIDOS, DNI, TELF, CORREO, DIREC,
                             FECNAC, EDAD, TIPOSEGURO, FECREGIS, HORAREGIS, IDADMI)
        VALUES(@IDPACIENTE, @NOMBRE, @APELLIDOS, @DNI, @TELF, @CORREO, @DIREC,
               @FECNAC, @EDAD, @TIPOSEGURO, CAST(GETDATE() AS DATE), CAST(GETDATE() AS TIME), @IDADMI)
        COMMIT TRANSACTION
        PRINT 'PACIENTE REGISTRADO CORRECTAMENTE'
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION
        SELECT ERROR_NUMBER()    AS NUMERO_ERROR,
               ERROR_MESSAGE()   AS MENSAJE_ERROR,
               ERROR_SEVERITY()  AS SEVERIDAD,
               ERROR_STATE()     AS ESTADO,
               ERROR_PROCEDURE() AS PROCEDIMIENTO,
               ERROR_LINE()      AS LINEA
    END CATCH
END
GO

