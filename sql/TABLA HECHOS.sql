CREATE TABLE DIM_SEGURO(
TIPOSEGURO CHAR(5) NOT NULL,
NOMBRESEGURO VARCHAR(25) NOT NULL,
DESCT DECIMAL(10,2) NOT NULL,
PRIMARY KEY(TIPOSEGURO))


CREATE TABLE DIM_PACIENTE(
IDPACIENTE CHAR(10) NOT NULL,
NOMBRE VARCHAR(25) NOT NULL,
APELLIDOS VARCHAR(25) NOT NULL,
DNI CHAR(8) NOT NULL,
EDAD INT NOT NULL,
DIREC VARCHAR(50) NOT NULL
PRIMARY KEY (IDPACIENTE))


CREATE TABLE DIM_MEDICO(
IDMEDICO CHAR(10) NOT NULL,
NOM_MEDICO VARCHAR(25) NOT NULL,
APE_MEDICO VARCHAR(25) NOT NULL,
NOM_ESPECI VARCHAR(20) NOT NULL,
PRIMARY KEY (IDMEDICO))


CREATE TABLE DIM_METODOPAGO(
IDMET_PAGO INT IDENTITY PRIMARY KEY,
IDPAGO CHAR (5) NOT NULL,
METODOPAGO VARCHAR(20) NOT NULL,
ESTADOPAGO VARCHAR(20) NOT NULL)


CREATE TABLE DIM_TIEMPO (
IDTIEMPO INT IDENTITY PRIMARY KEY,
FECHA DATE NOT NULL,
DIA INT NOT NULL,
MES INT NOT NULL,
NOMBRE_MES  VARCHAR(15) NOT NULL,
TRIMESTRE   INT NOT NULL,
AÑO       INT NOT NULL,
DIA_SEMANA  VARCHAR(15) NOT NULL)


CREATE TABLE TH_FACT_PAGO_CITA(
IDPACIENTE CHAR(10) NOT NULL,
IDMEDICO CHAR(10) NOT NULL,
TIPOSEGURO CHAR(5) NOT NULL,
IDMET_PAGO INT NOT NULL,
IDTIEMPO INT NOT NULL,
MONTO MONEY NOT NULL,
PAGO_FINAL MONEY NOT NULL,
TOTAL_CITAS INT NOT NULL,
FOREIGN KEY(IDPACIENTE) REFERENCES DIM_PACIENTE(IDPACIENTE),
FOREIGN KEY (IDMEDICO) REFERENCES DIM_MEDICO(IDMEDICO),
FOREIGN KEY (TIPOSEGURO) REFERENCES DIM_SEGURO(TIPOSEGURO),
FOREIGN KEY (IDMET_PAGO) REFERENCES DIM_METODOPAGO(IDMET_PAGO),
FOREIGN KEY (IDTIEMPO) REFERENCES DIM_TIEMPO(IDTIEMPO))

