INSERT INTO DIM_TIEMPO_FARMA (FECHA,DIA,MES,NOMBRE_MES,TRIMESTRE,AÑO,DIA_SEMANA)
SELECT DISTINCT
    CAST(PF.FECREGIS AS DATE),
    DAY(PF.FECREGIS),
    MONTH(PF.FECREGIS),
    DATENAME(MONTH, PF.FECREGIS),
    DATEPART(QUARTER, PF.FECREGIS),
    YEAR(PF.FECREGIS),
    DATENAME(WEEKDAY, PF.FECREGIS)
FROM PAGOFARMA PF
WHERE PF.FECREGIS IS NOT NULL;

UPDATE DIM_TIEMPO_FARMA
SET
    NOMBRE_MES = FORMAT(FECHA, 'MMMM', 'es-ES'),
    DIA_SEMANA = FORMAT(FECHA, 'dddd', 'es-ES');
GO


