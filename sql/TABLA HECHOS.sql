INSERT INTO TH_FACT_PAGO_CITA (IDPACIENTE, IDMEDICO, TIPOSEGURO, IDMET_PAGO, IDTIEMPO, MONTO, PAGO_FINAL, TOTAL_CITAS)
SELECT P.IDPACIENTE, C.IDMEDICO, P.TIPOSEGURO, DMP.IDMET_PAGO, DT.IDTIEMPO, PG.MONTO, PG.PAGO_FINAL,
    (SELECT COUNT(*)FROM PAGO PG2
    INNER JOIN CITA C2 ON PG2.IDCITA = C2.IDCITA
    WHERE C2.IDPACIENTE = P.IDPACIENTE AND PG2.ESTADOPAGO = 'Pagado' AND PG2.IDPAGO <= PG.IDPAGO) AS TOTAL_CITAS FROM PAGO PG
INNER JOIN CITA C ON PG.IDCITA = C.IDCITA
INNER JOIN PACIENTE P ON C.IDPACIENTE = P.IDPACIENTE
INNER JOIN DIM_METODOPAGO DMP ON PG.IDPAGO = DMP.IDPAGO
INNER JOIN DIM_TIEMPO DT ON DMP.IDMET_PAGO = DT.IDTIEMPO
WHERE PG.ESTADOPAGO = 'Pagado'
ORDER BY P.IDPACIENTE ASC;
GO


