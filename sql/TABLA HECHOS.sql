INSERT INTO TH_FACT_PAGO_FARMA
(IDPAGOFARMA, IDPACIENTE, IDFARMACEU, IDMEDICAMENTO, IDMETODO_FARMA, IDTIEMPO_FARMA, CANTIDAD, PRECIO_UNIDAD, TOTAL_PAGO)
SELECT PF.IDPAGOFARMA, PF.IDPACIENTE, PF.IDFARMACEU, AR.IDMEDICAMENTO, MP.IDMETODO_FARMA, DTF.IDTIEMPO_FARMA, AR.CANTIDAD, AR.PRECIOUNIDAD, PF.SUMATOTALDELPAGO 
FROM PAGOFARMA PF
INNER JOIN ATENCRECETA AR ON PF.IDATENCRECETA = AR.IDRECETA
INNER JOIN DIM_PACIENTE DP ON PF.IDPACIENTE = DP.IDPACIENTE
INNER JOIN DIM_FARMACEUTICA DF ON PF.IDFARMACEU = DF.IDFARMACEU
INNER JOIN DIM_MEDICAMENTO DM ON AR.IDMEDICAMENTO = DM.IDMEDICAMENTO
INNER JOIN DIM_METODO_PAGO_FARMA MP ON PF.METOPAGO = MP.METOPAGO_FARMA
INNER JOIN DIM_TIEMPO_FARMA DTF ON CAST(PF.FECREGIS AS DATE) = DTF.FECHA
WHERE PF.FECREGIS IS NOT NULL;
GO



