CREATE TABLE DIM_FARMACEUTICA(
IDFARMACEU CHAR(5) NOT NULL,
NOMBREF VARCHAR(25) NOT NULL,
APELLF VARCHAR(25) NOT NULL,
PRIMARY KEY(IDFARMACEU)
);


CREATE TABLE DIM_MEDICAMENTO(
IDMEDICAMENTO CHAR(5) NOT NULL,
NOMMEDICAM VARCHAR(25) NOT NULL,
GRAMOSPASTILLA DECIMAL(10,0) NOT NULL,
PRECIOUNIDAD DECIMAL(10,0) NOT NULL,
PRIMARY KEY(IDMEDICAMENTO)
);


CREATE TABLE DIM_METODO_PAGO_FARMA(
IDMETODO_FARMA INT IDENTITY(1,1) PRIMARY KEY,
METOPAGO_FARMA VARCHAR(20) NOT NULL
);


CREATE TABLE DIM_TIEMPO_FARMA (
IDTIEMPO_FARMA INT IDENTITY PRIMARY KEY,
FECHA DATE NOT NULL,
DIA INT NOT NULL,
MES INT NOT NULL,
NOMBRE_MES VARCHAR(15) NOT NULL,
TRIMESTRE INT NOT NULL,
AÑO INT NOT NULL,
DIA_SEMANA VARCHAR(15) NOT NULL
);


CREATE TABLE TH_FACT_PAGO_FARMA(
IDPAGOFARMA CHAR(5) NOT NULL,
IDPACIENTE CHAR(10) NOT NULL,
IDFARMACEU CHAR(5) NOT NULL,
IDMEDICAMENTO CHAR(5) NOT NULL,
IDMETODO_FARMA INT NOT NULL,
IDTIEMPO_FARMA INT NOT NULL,
CANTIDAD INT NOT NULL,
PRECIO_UNIDAD DECIMAL(10,2) NOT NULL,
TOTAL_PAGO DECIMAL(10,2) NOT NULL,
PRIMARY KEY(IDPAGOFARMA, IDMEDICAMENTO),
FOREIGN KEY(IDPACIENTE) REFERENCES DIM_PACIENTE(IDPACIENTE),
FOREIGN KEY(IDFARMACEU) REFERENCES DIM_FARMACEUTICA(IDFARMACEU),
FOREIGN KEY(IDMEDICAMENTO) REFERENCES DIM_MEDICAMENTO(IDMEDICAMENTO),
FOREIGN KEY(IDMETODO_FARMA) REFERENCES DIM_METODO_PAGO_FARMA(IDMETODO_FARMA),
FOREIGN KEY(IDTIEMPO_FARMA) REFERENCES DIM_TIEMPO_FARMA(IDTIEMPO_FARMA)
);

