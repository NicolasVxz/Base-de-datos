INSERT INTO DIM_TIEMPO (FECHA, DIA, MES, NOMBRE_MES, TRIMESTRE, AÑO, DIA_SEMANA)
SELECT PG.FECHAPAGO, DAY(PG.FECHAPAGO), MONTH(PG.FECHAPAGO), DATENAME(MONTH, PG.FECHAPAGO),DATEPART(QUARTER, PG.FECHAPAGO),
YEAR(PG.FECHAPAGO), DATENAME(WEEKDAY, PG.FECHAPAGO) FROM PAGO PG
WHERE PG.ESTADOPAGO = 'Pagado'
ORDER BY PG.FECHAPAGO, PG.IDPAGO;
GO
